# Source-only packaging/performance gate; real Windows RAM and installer QA are separate.
$ErrorActionPreference = "Stop"
$root = (Get-Item $PSScriptRoot).Parent.FullName
function Read([string]$p) { Get-Content -LiteralPath (Join-Path $root $p) -Raw }
function Require([string]$body, [string]$pattern, [string]$why) {
    if ($body -notmatch $pattern) { throw "Flick release source contract FAILED: $why" }
}
$media = Read "src/LocalClip.Core/Media/MediaProber.cs"
$xaml = Read "src/LocalClip.App/MainWindow.xaml"
$view = Read "src/LocalClip.App/MainWindow.xaml.cs"
$posterView = Read "src/LocalClip.App/MainWindow.LibraryPresentation.cs"
$decode = Read "src/LocalClip.App/Services/ThumbnailImageConverter.cs"
$asyncDecode = Read "src/LocalClip.App/Services/BoundedThumbnailLoader.cs"
$monitor = Read "src/LocalClip.Core/Diagnostics/ResourceMonitor.cs"
$package = Read "scripts/build_package.ps1"
$csproj = Read "src/LocalClip.App/LocalClip.App.csproj"
$install = Read "installer/Flick.iss"
$start = Read "src/LocalClip.App/Services/WindowsStartupRegistration.cs"
Require $media 'force_original_aspect_ratio=decrease' "FFmpeg thumbnails must be bounded"
Require $decode 'DecodePixelWidth\s*=\s*256' "Legacy thumbnails must decode to display size"
Require $xaml 'AsyncThumbnail.Path="\{Binding ThumbnailPath\}"' "Virtualized library rows must use the bounded asynchronous still loader"
Require $xaml 'AsyncThumbnail.Path="\{Binding SelectedClip.ThumbnailPath\}"' "The lazy player poster must use the same bounded asynchronous loader"
Require $asyncDecode 'BitmapSource.Create' "Cached still pixels must not retain encoded image streams"
Require $xaml 'Delay=180' "Search should debounce"
Require $view 'MediaElement.Source opens a decoder' "Editor must defer media until playback"
Require $posterView 'PlayerPoster.Visibility\s*=\s*Visibility.Visible' "Known available clips need the lazy poster"
Require $posterView 'HasKnownAvailability' "Unknown source availability must remain distinct from Offline"
Require $view 'ReleasePosterWhileHidden' "Tray/minimize should release decoded poster resources"
Require $monitor 'using var current' "Transient process handles must be disposed"
Require $package 'Flick.ico' "Portable packaging must include brand icon"
Require $package 'LICENSE-NOTICE.md' "Redistributable needs its original-source licensing notice"
Require $csproj 'AssemblyName>Flick<' "Branded apphost must be Flick.exe"
Require $install 'PrivilegesRequired=lowest' "Installer must be per user"
Require $install 'ArchitecturesAllowed=x64os' "Installer must disallow ARM and 32-bit processors"
Require $install 'InfoBeforeFile=PREVIEW-SYSTEM-REQUIREMENTS.txt' "Show compatibility notice before installation"
Require $install 'RemoveFlickProfile' "Opt-in uninstall cache cleanup must exist"
Require $install 'UninstallSilent' "Silent uninstalls preserve user data by default"
Require $install 'CurUninstallStepChanged' "Cleanup installed startup Run entry"
Require $install 'Uninstall Flick' "Windows Start Menu must link to standard uninstaller"
$settingsUi = Read "src/LocalClip.App/Views/SettingsWindow.xaml"
$settingsCode = Read "src/LocalClip.App/Views/SettingsWindow.xaml.cs"
$launcher = Read "src/LocalClip.App/Services/FlickUninstallLauncher.cs"
Require $settingsUi 'Uninstall Flick' "General Settings needs app uninstall action"
Require $settingsCode 'UninstallRequested' "Uninstall must require explicit user confirmation"
Require $launcher 'RegistryKey.OpenBaseKey' "Uninstall lookup must check explicit Windows Registry views"
Require $launcher 'RegistryHive.CurrentUser' "Uninstaller lookup must remain per-user"
Require $launcher 'unins000.exe' "Do not attempt self-delete outside Windows uninstaller"
Require $launcher 'RegistryView.Registry32' "Uninstall button must handle per-user 32-bit Inno registry view"
Require $launcher 'RegistryView.Registry64' "Uninstall button must handle per-user 64-bit registry view"
Require $install 'HKCU32' "Remove owned startup Run entry in the Inno 32-bit view"
Require $install 'HKCU64' "Remove owned startup Run entry in the Inno 64-bit view"

Require $install 'DefaultDirName=\{localappdata\}\\Programs\\Flick' "Program and user metadata must be separate"
Require $start 'Environment.ProcessPath' "Startup must use the running executable path"
$visual = Read "scripts/capture_flick_visual_evidence.ps1"
$performance = Read "scripts/sample_flick_performance.ps1"
Require $visual 'Flick", "LocalClip.App' "Screenshot QA must accept branded Flick.exe"
Require $performance 'Flick", "LocalClip.App' "Performance QA must accept branded Flick.exe"
if ($install -match '(?im)^\s*UninstallDelete|deleteall') {
    throw "Do not broadly delete user files on uninstall"
}
# Version, filenames and release links must agree (not just compile).
$lock = Read "dependencies.lock.json"
$setupScript = Read "scripts/build_installer.ps1"
$versions = Read "release/preview-version.txt"
Require $csproj '<Version>1\.0\.12-preview\.1</Version>' "App assembly version must match preview tag"
Require $install 'MyAppVersion "1\.0\.12"' "Inno Setup AppVersion must match"
Require $package 'Flick-v1\.0\.12-win-x64' "Portable version must match installer"
Require $setupScript 'Flick-Setup\.exe' "User-facing installer must be a single EXE"
Require $lock '1\.0\.12-preview\.1' "Pinned app version must match tag"
$nativeVersion = Read "src/LocalClip.CaptureHost/capture_version.h"
Require $nativeVersion '#define FLICK_FILE_VERSION 1,0,12,0' "Native numeric file version must match managed version"
Require $nativeVersion '#define FLICK_PRODUCT_VERSION 1,0,12,0' "Native numeric product version must match managed version"
if ($versions.Trim() -ne "1.0.12-preview.1") { throw "Release version manifest does not match compiled version" }
Write-Host "Flick packaging and memory source contracts PASS (not a hardware performance test)." -ForegroundColor Green

# No automatic unsigned GitHub Releases may be created after SAC block report.
$legacyRelease = Read ".github/workflows/publish-preview-release.yml"
$signedWorkflow = Read ".github/workflows/signed-windows-qa.yml"
$signingImpl = Read "scripts/build_trusted_flick_preview.ps1"
$trustAudit = Read "scripts/verify_flick_trust.ps1"
if ($legacyRelease -match '(?im)^\s*-\s+''?release'',\s*''?create''?') {
    throw "Legacy unsigned workflow must not publish release binaries"
}
Require $legacyRelease 'workflow_dispatch:' "Legacy workflow must be manually invoked only"
Require $signedWorkflow 'flick-trusted-signing' "Signed candidate must use a protected GitHub environment"
Require $signedWorkflow 'id-token: write' "Azure Public Trust uses OIDC, not exported private keys"
Require $signedWorkflow 'prepare_flick_signing\.ps1' "Prepare the CA signing client before building"
Require $signingImpl 'RequireTrustedSigning' "Inno must sign Setup and Uninstaller"
Require $trustAudit 'Get-AuthenticodeSignature' "Public release gate must verify trusted signatures"
Write-Host "Legacy automatic unsigned publishing stays disabled; verified previews use the separately approved publication workflow." -ForegroundColor Yellow
